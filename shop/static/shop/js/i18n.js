/* ── i18n Engine ── */
const LANG_NAMES = {
    uk: '🇺🇦 Українська',
    en: '🇬🇧 English',
    de: '🇩🇪 Deutsch',
    pl: '🇵🇱 Polski',
    cs: '🇨🇿 Čeština',
    es: '🇪🇸 Español'
};

const LANG_FLAGS = {
    uk: '🇺🇦', en: '🇬🇧', de: '🇩🇪', pl: '🇵🇱', cs: '🇨🇿', es: '🇪🇸'
};

function getCurrentLang() {
    return localStorage.getItem('store3d_lang') || 'uk';
}

function t(key) {
    const entry = I18N[key];
    if (!entry) return key;
    const lang = getCurrentLang();
    return entry[lang] || entry['uk'] || key;
}

window.getI18nText = t;

function setLanguage(lang) {
    if (!LANG_NAMES[lang]) return;
    localStorage.setItem('store3d_lang', lang);
    applyTranslations();
    updateLangSwitcher();
    updatePrices(lang);
}

function applyTranslations() {
    const lang = getCurrentLang();

    // Translate all elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        const entry = I18N[key];
        if (!entry) return;
        const text = entry[lang] || entry['uk'];
        if (text) {
            // For inputs — translate placeholder
            if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                el.placeholder = text;
            } else if (el.tagName === 'OPTION') {
                el.textContent = text;
            } else {
                el.textContent = text;
            }
        }
    });

    // Translate placeholders specifically
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        const entry = I18N[key];
        if (entry) {
            el.placeholder = entry[lang] || entry['uk'];
        }
    });

    // Update html lang attribute
    document.documentElement.lang = lang;
}

function updateLangSwitcher() {
    const lang = getCurrentLang();
    const currentFlag = document.getElementById('lang-current-flag');
    const dropdown = document.getElementById('lang-dropdown');
    if (currentFlag) {
        currentFlag.textContent = LANG_FLAGS[lang] || '🌐';
    }
    if (dropdown) {
        dropdown.querySelectorAll('.lang-option').forEach(opt => {
            opt.classList.toggle('lang-option--active', opt.dataset.lang === lang);
        });
    }
}

function toggleLangDropdown(e) {
    e.stopPropagation();
    const dropdown = document.getElementById('lang-dropdown');
    if (dropdown) {
        dropdown.classList.toggle('open');
    }
}

// Close dropdown on outside click
document.addEventListener('click', function(e) {
    if (!e.target.closest('.lang-switcher')) {
        const dropdown = document.getElementById('lang-dropdown');
        if (dropdown) dropdown.classList.remove('open');
    }
});

// ─── Currency logic ───
const CURRENCIES = {
    uk: { sym: '₴', code: 'UAH' },
    en: { sym: '$', code: 'USD' },
    de: { sym: '€', code: 'EUR' },
    pl: { sym: 'zł', code: 'PLN' },
    cs: { sym: 'Kč', code: 'CZK' },
    es: { sym: '€', code: 'EUR' }
};

let exchangeRates = null;

async function fetchExchangeRates() {
    try {
        const resp = await fetch('https://open.er-api.com/v6/latest/UAH');
        const data = await resp.json();
        if (data && data.rates) {
            exchangeRates = data.rates;
            updatePrices(getCurrentLang());
        }
    } catch (err) {
        console.error('Failed to load exchange rates', err);
    }
}

function updatePrices(lang) {
    const displays = document.querySelectorAll('.price-display');
    if (!displays.length) return;

    const curr = CURRENCIES[lang] || CURRENCIES['uk'];
    
    // Default fallback rates if API fails
    const defaultRates = {
        UAH: 1,
        USD: 0.025,
        EUR: 0.023,
        PLN: 0.1,
        CZK: 0.59
    };
    
    const rate = exchangeRates ? exchangeRates[curr.code] : defaultRates[curr.code];
    
    displays.forEach(el => {
        const uahPrice = parseFloat(el.getAttribute('data-price-uah'));
        if (isNaN(uahPrice)) return;
        
        let converted = uahPrice * rate;
        
        // Formatting:
        // No decimals for UAH, CZK, otherwise 2 decimals
        let formatted;
        if (curr.code === 'UAH' || curr.code === 'CZK') {
            formatted = Math.round(converted);
        } else {
            formatted = converted.toFixed(2);
        }
        
        el.textContent = formatted;
        // Update symbol next to it
        if (el.nextSibling && el.nextSibling.nodeType === 3) {
            el.nextSibling.textContent = ' ' + curr.sym;
        }
    });
}

// Initialize on DOM ready
document.addEventListener('DOMContentLoaded', function() {
    applyTranslations();
    updateLangSwitcher();
    fetchExchangeRates(); // Will update prices when rates load
});
